-- Reference schema for an EMPTY test database; never applied by deployment.
-- Existing production schemas are inspected read-only by preflight.
CREATE TABLE SITE (
    id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    title VARCHAR(30) NOT NULL,
    welshTitle VARCHAR(100),
    alert VARCHAR(500),
    xsl VARCHAR(50) NOT NULL,
    selectorUrl VARCHAR(500) NOT NULL,
    pageUrl VARCHAR(500) NOT NULL,
    powersaveSchedule VARCHAR(2000) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE CDU (
    id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    macAddress VARCHAR(17) NOT NULL,
    cduNumber VARCHAR(100) NOT NULL,
    title VARCHAR(30) NOT NULL,
    description VARCHAR(500),
    location VARCHAR(50) NOT NULL,
    url VARCHAR(255) NOT NULL,
    refresh INT NOT NULL,
    ipAddr VARCHAR(100),
    notification VARCHAR(500),
    xsl VARCHAR(50),
    fkSITE INT NOT NULL,
    FOREIGN KEY (fkSITE) REFERENCES SITE(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Required Model Court parser mapping; this is a synthetic test schema only.
CREATE TABLE urlMappings (
    cduID INT NOT NULL PRIMARY KEY,
    url VARCHAR(2000) NOT NULL,
    FOREIGN KEY (cduID) REFERENCES CDU(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE MAC_TO_IP (
    id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    ipAddress VARCHAR(100) NOT NULL,
    fkCDU INT NOT NULL,
    ts TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (fkCDU) REFERENCES CDU(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE AUDIT (
    id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    eventTimestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    username VARCHAR(50) NOT NULL,
    eventType VARCHAR(50) NOT NULL,
    eventData VARCHAR(5000) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE CDU_LOGGER (
    id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    eventTimestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    macAddress VARCHAR(17) NOT NULL,
    pageIndex INT,
    errorCode VARCHAR(50) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE PROXY_LOGGER (
    id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    eventTimestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    macAddress VARCHAR(17) NOT NULL,
    pageIndex INT,
    errorCode VARCHAR(50) NOT NULL,
    errorMsg VARCHAR(500) NOT NULL,
    url VARCHAR(500),
    xhibitResponse VARCHAR(5000)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
